package dev.sethan8r.grammar.app.ui.theme

/**
 * Единые токены прозрачности (наряду с [Dimens] и [Color]). Все полупрозрачные подложки/скримы
 * берут alpha отсюда — смена дизайна правит токен, не экраны. Сырые `alpha = 0.7f` в Composable
 * не пишем.
 */
object Alphas {

    /**
     * Подложка плавающего футера с кнопкой: контент, уезжающий под кнопку, затемняется, но
     * остаётся виден (не сплошная чёрная плашка). Значение подбирается на глаз.
     */
    const val footerScrim = 0.65f

    /**
     * Заливка центра выделенного варианта ответа (выбран/верный/неверный): фон = цвет обводки с этой
     * прозрачностью. Border остаётся сплошным — центр лишь подкрашивается, не заливается целиком.
     */
    const val answerFill = 0.2f

    /** Начальная непрозрачность чёрного ореола-тени вокруг парящего элемента (у края, дальше в ноль). */
    const val halo = 0.3f

    /** Верх градиента-скрима над строкой состояния (гасит контент, проезжающий под неё); к низу — в ноль. */
    const val statusScrim = 1f

    /** Затемнение закреплённой шапки, под которую проезжает список (`PinnedHeader`). */
    const val headerScrim = 0.8f

    /** Нижняя точка пульсации точки «AI печатает» (гаснет до неё и разгорается обратно). */
    const val typingDotMin = 0.3f

    /** Затемнение фрейма готового вопроса внутри акцентной реплики пользователя. */
    const val optionFrame = 0.15f

    /** Обводка ярлыка хода внутри реплики диалога теории: цвет текста реплики, приглушённый до рамки. */
    const val dialogNoteBorder = 0.35f

    /** Сам ярлык хода — тем же цветом, что реплика, но тише её. */
    const val dialogNoteText = 0.75f
}