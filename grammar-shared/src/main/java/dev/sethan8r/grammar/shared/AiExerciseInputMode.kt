package dev.sethan8r.grammar.shared

/**
 * Способ ввода ответа на AI-упражнение — enum контракта клиент↔сервер.
 *
 * Лежит в grammar-shared (а не в app), потому что им оперируют обе стороны: клиент хранит его
 * в content.db (`AiExercise.inputMode`) и рендерит зону ввода, сервер по нему понимает, нужно
 * ли возвращать сегменты для пропусков. Контракт един — расходиться сторонам нельзя.
 *
 * Источник правды по семантике — db_schema.md → ENUM `AiExerciseInputMode`.
 */
enum class AiExerciseInputMode {

    /**
     * Пользователь пишет ответ в свободное поле снизу.
     * Перевод предложения, составить вопрос, исправить ошибку — любой произвольный текст.
     */
    FREE_WRITE,

    /**
     * AI присылает текст с пропусками `[___]`; сервер парсит их в сегменты, клиент рендерит
     * Text() и встроенные TextField() в одну строку. Редактируются только пропуски.
     */
    FILL_BLANKS
}